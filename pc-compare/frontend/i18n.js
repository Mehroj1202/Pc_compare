/* t("kalit", {o'zgaruvchi: qiymat}) — joriy tildagi matnni qaytaradi */
function t(key, vars) {
  const d = I18N.dict;
  let s = (d[I18N.lang] && d[I18N.lang][key]);
  if (s === undefined) s = d.uz[key];
  if (s === undefined) s = key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m));
  return s;
}

